import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { codeToKeyedTokens } from '@shikijs/magic-move/core'
import { createJiti } from 'jiti'
import { createHighlighter } from 'shiki'

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const jsonOutputPath = resolve(siteDir, 'app/utils/magic-tokens.generated.json')
const tsOutputPath = resolve(siteDir, 'app/utils/magic-tokens.generated.ts')
const jiti = createJiti(import.meta.url)

const { contractSteps, magicCodeBlocks } = await jiti.import(
  resolve(siteDir, 'app/utils/snippets.ts'),
)

const highlighter = await createHighlighter({
  themes: ['github-light-default', 'github-dark-default'],
  langs: ['ts', 'vue'],
})

const magicTokens = Object.fromEntries(
  magicCodeBlocks.map((block) => {
    return [
      block.codeKey,
      {
        light: contractSteps.map((step) => {
          return codeToKeyedTokens(
            highlighter,
            step[block.codeKey],
            { lang: block.lang, theme: 'github-light-default' },
            false,
          )
        }),
        dark: contractSteps.map((step) => {
          return codeToKeyedTokens(
            highlighter,
            step[block.codeKey],
            { lang: block.lang, theme: 'github-dark-default' },
            false,
          )
        }),
      },
    ]
  }),
)

const tsSource = `/* eslint-disable */\n// This file is generated by site/scripts/generate-magic-tokens.mjs.\n// Do not edit by hand.\nimport type { KeyedTokensInfo } from '@shikijs/magic-move/core'\nimport type { magicCodeBlocks } from './snippets'\nimport tokens from './magic-tokens.generated.json'\n\ntype CodeTheme = 'light' | 'dark'\ntype CodeBlockKey = (typeof magicCodeBlocks)[number]['codeKey']\n\nexport const magicTokens = tokens as Record<CodeBlockKey, Record<CodeTheme, KeyedTokensInfo[]>>\n`

await mkdir(dirname(jsonOutputPath), { recursive: true })
await writeFile(jsonOutputPath, `${JSON.stringify(magicTokens, null, 2)}\n`)
await writeFile(tsOutputPath, tsSource)
